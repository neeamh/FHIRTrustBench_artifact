"""Generate the evidence-map heatmap (TikZ) from reports/scores_by_study.csv.

Usage (from the artifact root):
    python scripts/make_evidence_map.py > evidence_map.tex
Needs \\usepackage{tikz} and \\usepackage{pifont} in the preamble. Colours are defined
inside the figure, so the preamble needs no colour definitions.
"""
import csv, os, statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIMS = ["FS", "AV", "WI", "TE", "GR"]
NAMES = {"S01": "Henry 2018", "S02": "Gruendner 2019", "S03": "Rajkomar 2018", "S04": "Tarumi 2021",
         "S05": "Wang 2022", "S06": "Sun 2022", "S07": "Yoo 2022", "S08": "Toro Beltran 2022",
         "S09": "McMurry 2024", "S10": "Li 2024", "S11": "Jiang 2025", "S12": "Engelke 2025",
         "S13": "Schmiedmayer 2025", "S14": "Wen 2025", "S15": "Kabak 2025", "S16": "Lee 2026"}
# muted red-orange-yellow ramp: red = little evidence, pale yellow = most evidence
BINS = [(0, 0, "ftbS0"), (1, 24, "ftbS1"), (25, 49, "ftbS2"), (50, 74, "ftbS3"), (75, 100, "ftbS4")]
DARK = {"ftbS0", "ftbS1"}

rows = list(csv.DictReader(open(os.path.join(ROOT, "reports", "scores_by_study.csv"))))
for r in rows:
    for d in DIMS:
        r[d] = None if r[d] == "" else round(float(r[d]) * 100)
rows.sort(key=lambda r: (-r["FS"], NAMES[r["study"]]))

X0, W, H, LABEL_W = 2.55, 0.86, 0.36, 2.5
xg = X0 + W * len(DIMS) + 0.58  # gate column centre
o = []
p = o.append
p("% ---- FHIRTrustBench evidence map (generated by results/scripts/make_evidence_map.py; locked 2026-10-26 data) ----")
p("% Preamble: \\usepackage{tikz}, \\usepackage{pifont}")
p("\\definecolor{ftbS0}{HTML}{A8443A}\\definecolor{ftbS1}{HTML}{D06E45}\\definecolor{ftbS2}{HTML}{E9A05A}")
p("\\definecolor{ftbS3}{HTML}{F2C674}\\definecolor{ftbS4}{HTML}{F8E6AE}\\definecolor{ftbSNA}{HTML}{FFFFFF}")
p("\\definecolor{ftbSInk}{HTML}{2E2E2E}\\definecolor{ftbSRule}{HTML}{B8B8B8}")
p("\\begin{figure}[t]\n\\centering")
p("\\begin{tikzpicture}[x=1cm,y=1cm,font=\\scriptsize\\sffamily]")
p(f"\\node[anchor=south west,font=\\scriptsize\\sffamily\\bfseries] at (0,0.04) {{Study}};")
for j, d in enumerate(DIMS):
    p(f"\\node[anchor=south,font=\\scriptsize\\sffamily\\bfseries] at ({X0+W*j+W/2:.2f},0.04) {{{d}}};")
p(f"\\node[anchor=south,font=\\scriptsize\\sffamily\\bfseries] at ({xg:.2f},0.04) {{FS gate}};")
for i, r in enumerate(rows):
    y0, y1 = -H * i, -H * (i + 1)
    yc = (y0 + y1) / 2
    p(f"\\node[anchor=west,text=ftbSInk] at (0,{yc:.2f}) {{{NAMES[r['study']]}}};")
    for j, d in enumerate(DIMS):
        xa, xb = X0 + W * j, X0 + W * (j + 1)
        v = r[d]
        if v is None:
            p(f"\\fill[ftbSNA] ({xa:.2f},{y1:.2f}) rectangle ({xb:.2f},{y0:.2f});")
            p(f"\\node[text=black!40] at ({(xa+xb)/2:.2f},{yc:.2f}) {{--}};")
        else:
            col = next(c for lo, hi, c in BINS if lo <= v <= hi)
            txt = "white" if col in DARK else "ftbSInk"
            p(f"\\fill[{col}] ({xa:.2f},{y1:.2f}) rectangle ({xb:.2f},{y0:.2f});")
            p(f"\\node[text={txt}] at ({(xa+xb)/2:.2f},{yc:.2f}) {{{v}}};")
    mark = "\\ding{51}~pass" if r["gate"] == "PASS" else "\\ding{55}~fail"
    p(f"\\node[text=ftbSInk] at ({xg:.2f},{yc:.2f}) {{{mark}}};")
n = len(rows)
yb = -H * n
for i in range(n + 1):
    p(f"\\draw[white,line width=0.9pt] ({X0:.2f},{-H*i:.2f}) -- ({X0+W*len(DIMS):.2f},{-H*i:.2f});")
for j in range(len(DIMS) + 1):
    p(f"\\draw[white,line width=0.9pt] ({X0+W*j:.2f},0) -- ({X0+W*j:.2f},{yb:.2f});")
p(f"\\draw[ftbSRule,line width=0.3pt] ({X0:.2f},0) rectangle ({X0+W*len(DIMS):.2f},{yb:.2f});")
p(f"\\draw[black!60,line width=0.4pt] (0,{yb-0.06:.2f}) -- ({xg+0.55:.2f},{yb-0.06:.2f});")
ym = yb - 0.27
p(f"\\node[anchor=west,font=\\scriptsize\\sffamily\\bfseries] at (0,{ym:.2f}) {{Median}};")
for j, d in enumerate(DIMS):
    v = [r[d] for r in rows if r[d] is not None]
    med = statistics.median([float(x) for x in v])
    lab = f"{med:.0f}\\%" + ("$^{*}$" if len(v) < n else "")
    p(f"\\node[font=\\scriptsize\\sffamily\\bfseries] at ({X0+W*j+W/2:.2f},{ym:.2f}) {{{lab}}};")
npass = sum(r["gate"] == "PASS" for r in rows)
p(f"\\node[font=\\scriptsize\\sffamily\\bfseries] at ({xg:.2f},{ym:.2f}) {{{npass}/{n} pass}};")
yl = ym - 0.55
p(f"\\node[anchor=west] at (0,{yl:.2f}) {{Score (\\%)}};")
LEG = [1.40, 2.10, 3.20, 4.45, 5.70]
for (lo, hi, c), x in zip(BINS, LEG):
    lab = "0" if hi == 0 else f"{lo}--{hi}"
    p(f"\\fill[{c}] ({x:.2f},{yl-0.11:.2f}) rectangle ({x+0.28:.2f},{yl+0.11:.2f});")
    p(f"\\draw[ftbSRule,line width=0.2pt] ({x:.2f},{yl-0.11:.2f}) rectangle ({x+0.28:.2f},{yl+0.11:.2f});")
    p(f"\\node[anchor=west] at ({x+0.29:.2f},{yl:.2f}) {{{lab}}};")
x = 7.12
p(f"\\draw[ftbSRule,line width=0.2pt] ({x:.2f},{yl-0.11:.2f}) rectangle ({x+0.28:.2f},{yl+0.11:.2f});")
p(f"\\node[text=black!40] at ({x+0.14:.2f},{yl:.2f}) {{--}};")
p(f"\\node[anchor=west] at ({x+0.29:.2f},{yl:.2f}) {{NA}};")
p("\\end{tikzpicture}")
p("\\caption{FHIRTrustBench applied to 16 published FHIR-integrated clinical AI systems, using the adjudicated codes. "
  "Each cell is the share of attainable points on the applicable sub-criteria of a dimension (Met = 2, Partial = 1, "
  "not met or not reported = 0); rows are sorted by FHIR specificity. No system passes the FHIR-specificity gate "
  "(FS1 and FS3 at least Partial and FS $\\geq$ 50\\%); the highest FS score is 44\\%. "
  "-- = fewer than three applicable sub-criteria; $^{*}$ median over the eight studies with a defined GR score.}")
p("\\Description{A heatmap with 16 studies as rows and the five FHIRTrustBench dimensions as columns. "
  "Most cells fall in the 0 to 49 percent bands, governance is undefined for half of the studies, "
  "and every study is marked as failing the FHIR-specificity gate.}")
p("\\label{fig:evidencemap}")
p("\\end{figure}")
print("\n".join(o))
